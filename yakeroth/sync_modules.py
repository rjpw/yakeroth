"""Module synchronization - resolves modules.yml, clones, generates CMake, copies SQL/configs."""

import logging
import shutil
import subprocess
from pathlib import Path
from typing import Optional

import yaml
from git import Repo

from .models import ModuleLock, ModulesLockFile, ModuleSpec, ModulesFile
from .git_utils import GitError, clone_or_update, get_repo, ls_remote_commit, stage_all, commit as git_commit, tag as git_tag

logger = logging.getLogger(__name__)


class SyncError(Exception):
    """Module sync failed."""
    pass


def load_modules_yml(site_dir: Path) -> ModulesFile:
    """Load modules.yml from site directory."""
    modules_file = site_dir / "modules.yml"
    if not modules_file.exists():
        return ModulesFile(modules=[])

    with open(modules_file) as f:
        data = yaml.safe_load(f) or {}
    
    # Handle case where modules key exists but is null (commented out)
    if data.get("modules") is None:
        data["modules"] = []
        
    return ModulesFile.model_validate(data)


def load_modules_lock(site_dir: Path) -> ModulesLockFile:
    """Load modules.lock.yml from site directory."""
    lock_file = site_dir / "modules.lock.yml"
    if not lock_file.exists():
        return ModulesLockFile(modules=[])

    with open(lock_file) as f:
        data = yaml.safe_load(f) or {}
    return ModulesLockFile.model_validate(data)



def write_modules_lock(site_dir: Path, lock_file: ModulesLockFile) -> None:
    """Write modules.lock.yml to site directory."""
    lock_path = site_dir / "modules.lock.yml"
    data = lock_file.model_dump(exclude_none=True)
    with open(lock_path, "w") as f:
        f.write("# modules.lock.yml - DO NOT EDIT MANUALLY\n")
        f.write("# Generated by yakeroth sync\n")
        yaml.dump(data, f, sort_keys=False, default_flow_style=False)

def resolve_module_commit(spec: ModuleSpec) -> str:
    """Resolve module spec to a commit SHA."""
    if spec.commit:
        return spec.commit

    ref = spec.branch
    commit = ls_remote_commit(spec.source, ref)
    logger.info(f"Resolved {spec.name}@{ref} -> {commit[:12]}")
    return commit


def clone_module(spec: ModuleSpec, commit: str, modules_dir: Path) -> Path:
    """Clone or update module to specific commit."""
    dest = modules_dir / (spec.dirname or spec.name)
    try:
        clone_or_update(spec.source, dest, commit, spec.branch)
        return dest
    except GitError as e:
        raise SyncError(f"Failed to clone {spec.name}: {e}") from e


def copy_sql_files(module_path: Path, spec: ModuleSpec, sql_dir: Path) -> list[Path]:
    """Copy SQL files from module to site sql/custom/{db_auth,db_characters,db_world}/."""
    copied = []
    for sql_rel in spec.sql:
        src = module_path / sql_rel
        if not src.exists():
            logger.warning(f"SQL file not found in {spec.name}: {sql_rel}")
            continue

        # Determine target subdirectory from path
        # e.g., data/sql/db_world/mod_playerbots.sql -> sql/custom/db_world/
        parts = sql_rel.split("/")
        db_dir = "db_world"  # default
        for part in parts:
            if part.startswith("db_"):
                db_dir = part
                break

        target_dir = sql_dir / "custom" / db_dir
        target_dir.mkdir(parents=True, exist_ok=True)
        target = target_dir / src.name

        shutil.copy2(src, target)
        copied.append(target)
        logger.debug(f"Copied {sql_rel} -> {target.relative_to(sql_dir)}")

    return copied


def copy_config_files(module_path: Path, spec: ModuleSpec, env_dir: Path) -> list[Path]:
    """Copy module config files to env/modules/ for bind-mount."""
    copied = []
    config_dirs = [
        module_path / "etc",
        module_path / "config",
        module_path / "conf",
    ]

    for config_dir in config_dirs:
        if not config_dir.exists():
            continue

        for config_file in config_dir.rglob("*.conf*"):
            rel = config_file.relative_to(config_dir)
            target = env_dir / "modules" / spec.name / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(config_file, target)
            copied.append(target)
            logger.debug(f"Copied config {config_file} -> {target.relative_to(env_dir)}")

    return copied


def generate_cmake(specs: list[tuple[ModuleSpec, ModuleLock]], modules_dir: Path, output: Path) -> None:
    """Generate ModulesSite.cmake that adds all modules to build."""
    lines = [
        "# ModulesSite.cmake - Generated by yakeroth sync",
        "# DO NOT EDIT MANUALLY",
        "",
        "# Add site modules to build",
        "list(APPEND AC_MODULES",
    ]

    for spec, lock in specs:
        lines.append(f'    "{lock.dirname}"  # {spec.source}@{lock.commit[:12]}')

    lines.append(")")
    lines.append("")

    # Set build type for each module
    for spec, lock in specs:
        cmake_name = lock.dirname.upper().replace("-", "_")
        if spec.build == "dynamic":
            lines.append(f'set({cmake_name}_BUILD_TYPE "SHARED")')
        else:
            lines.append(f'set({cmake_name}_BUILD_TYPE "STATIC")')

    output.write_text("\n".join(lines) + "\n")
    logger.info(f"Generated {output}")


def apply_patches(spec: ModuleSpec, module_path: Path, patches_dir: Path) -> None:
    """Apply patch file if specified."""
    if not spec.patch:
        return

    patch_file = patches_dir / spec.patch
    if not patch_file.exists():
        raise SyncError(f"Patch file not found: {patch_file}")

    try:
        subprocess.run(
            ["git", "apply", str(patch_file)],
            cwd=module_path,
            check=True,
            capture_output=True,
            text=True,
        )
        logger.info(f"Applied patch {spec.patch} to {spec.name}")
    except subprocess.CalledProcessError as e:
        raise SyncError(f"Failed to apply patch {spec.patch}: {e.stderr}") from e


def sync(site_dir: Path, auto_commit: bool = True) -> ModulesLockFile:
    """Main sync function - resolves, clones, generates files."""
    modules_yml = load_modules_yml(site_dir)
    repo = get_repo(site_dir)

    modules_dir = site_dir / "modules"
    sql_dir = site_dir / "sql"
    patches_dir = site_dir / "patches"
    env_dir = site_dir / "env"
    cmake_file = site_dir / "ModulesSite.cmake"

    # Clean generated directories (they'll be recreated)
    for d in [modules_dir, sql_dir / "custom", env_dir / "modules"]:
        if d.exists():
            shutil.rmtree(d)

    modules_dir.mkdir(parents=True, exist_ok=True)
    sql_dir.mkdir(parents=True, exist_ok=True)
    patches_dir.mkdir(parents=True, exist_ok=True)
    env_dir.mkdir(parents=True, exist_ok=True)

    # Resolve all modules
    resolved: list[tuple[ModuleSpec, ModuleLock]] = []
    for spec in modules_yml.modules:
        commit = resolve_module_commit(spec)
        lock = ModuleLock.from_spec(spec, commit)
        resolved.append((spec, lock))

    # Clone each module
    for spec, lock in resolved:
        module_path = clone_module(spec, lock.commit, modules_dir)
        apply_patches(spec, module_path, patches_dir)
        copy_sql_files(module_path, spec, sql_dir)
        copy_config_files(module_path, spec, env_dir)

    # Generate CMake include file
    generate_cmake(resolved, modules_dir, cmake_file)

    # Write lock file
    lock_file = ModulesLockFile(modules=[lock for _, lock in resolved])
    write_modules_lock(site_dir, lock_file)

    # Git commit if requested
    if auto_commit:
        try:
            stage_all(repo)
            git_commit(repo, "site: sync modules")
        except GitError as e:
            logger.warning(f"Git commit failed: {e}")

    return lock_file